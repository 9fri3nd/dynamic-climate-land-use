# --- gui text construction helpers --------------------------------------

def render(items, depth, indent="\t"):
    """Render nested (header, children) tuples and plain lines with indentation."""
    out = []
    for item in items:
        if isinstance(item, tuple):
            header, children = item
            out.append(indent * depth + header + " {")
            out.extend(render(children, depth + 1, indent))
            out.append(indent * depth + "}")
        elif item:
            out.append(indent * depth + item)
        else:
            out.append("")
    return out


def block(items, depth, indent="\t"):
    return "\n".join(render(items, depth, indent)) + "\n"


def script_value(name, root="LocationView.GetLocation"):
    return "GuiScope.SetRoot(%s.MakeScope).ScriptValue('%s')" % (root, name)


def script_value_float(name, root="LocationView.GetLocation"):
    return "FixedPointToFloat(%s)" % script_value(name, root)


def vis_gt(name, bound, root="LocationView.GetLocation"):
    return 'visible = "[GreaterThan_float(%s, \'(float)%s\')]"' % (
        script_value_float(name, root), bound)


def vis_lt(name, bound, root="LocationView.GetLocation"):
    return 'visible = "[LessThan_float(%s, \'(float)%s\')]"' % (
        script_value_float(name, root), bound)


def vis_between(name, low, high, root="LocationView.GetLocation"):
    return 'visible = "[Between_float(%s, \'(float)%s\', \'(float)%s\')]"' % (
        script_value_float(name, root), low, high)


