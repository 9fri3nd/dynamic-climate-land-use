# --- patch engine --------------------------------------------------------

def read_normalized(path):
    try:
        text = path.read_text(encoding="utf-8-sig")
    except OSError as exc:
        raise PatchError("cannot read vanilla file %s: %s" % (path, exc))
    return text.replace("\r\n", "\n")


def write_bom(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(BOM + text.encode("utf-8"))


def insert_after(text, anchor, insertion, label):
    count = text.count(anchor)
    if count != 1:
        raise PatchError("%s: anchor occurs %d times (expected 1) — vanilla file changed?"
                         % (label, count))
    return text.replace(anchor, anchor + insertion)


def insert_before(text, anchor, insertion, label):
    count = text.count(anchor)
    if count != 1:
        raise PatchError("%s: anchor occurs %d times (expected 1) — vanilla file changed?"
                         % (label, count))
    return text.replace(anchor, insertion + anchor)


def extract_template(text, name):
    marker = "template %s {" % name
    count = text.count(marker)
    if count != 1:
        raise PatchError("template '%s': definition occurs %d times (expected 1)" % (name, count))
    start = text.index(marker)
    end = text.find("\n}\n", start)
    if end == -1:
        raise PatchError("template '%s': closing brace not found" % name)
    return text[start:end + 3]


def generate(vanilla_root, mod_root):
    vanilla_root = Path(vanilla_root)
    mod_root = Path(mod_root)
    written = []

    window = read_normalized(vanilla_root / WINDOW_REL)
    window = insert_after(window, TAB_ANCHOR, "\n" + block([TAB_BUTTON], 5),
                          "location_window.gui tab button")
    window = insert_before(window, PAGE_ANCHOR, block(["# DYNAMIC CLIMATE", DCL_PAGE], 4) + "\n",
                           "location_window.gui climate page")
    if not window.endswith("}\n"):
        raise PatchError("location_window.gui: does not end with '}' "
                         "(progressbar template append anchor)")
    window = window + "\n" + block([PROGRESSBAR_TEMPLATE], 0)
    dest = mod_root / WINDOW_REL
    write_bom(dest, WINDOW_HEADER + window)
    written.append(dest)

    tooltips = read_normalized(vanilla_root / TOOLTIPS_REL)
    template = extract_template(tooltips, TOOLTIP_TEMPLATE)
    rows = block(HOVER_ROWS, 1, indent="    ")
    out = TOOLTIP_HEADER + "\n" + template[:-2] + "\n" + rows + "}\n"
    dest = mod_root / TOOLTIP_OUT_REL
    write_bom(dest, out)
    written.append(dest)
    return written


def main(argv=None):
    here = Path(__file__).resolve()
    p = argparse.ArgumentParser(description="Generate the dcl GUI files from vanilla sources.")
    p.add_argument("--vanilla", default=os.environ.get("DCL_VANILLA_ROOT") or DEFAULT_VANILLA)
    p.add_argument("--mod-root", default=str(here.parents[1]))
    args = p.parse_args(argv)
    try:
        written = generate(args.vanilla, args.mod_root)
    except PatchError as exc:
        print("FAIL: %s" % exc)
        return 1
    for path in written:
        print("wrote %s" % path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
